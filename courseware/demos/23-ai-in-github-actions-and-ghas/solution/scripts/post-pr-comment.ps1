#Requires -Version 7.2
<#
.SYNOPSIS
    Posts a Markdown file as a comment on a GitHub pull request, or updates this workflow's earlier one.

.DESCRIPTION
    Runs in a GitHub Actions step after the agent step, with the GitHub CLI (gh), which GitHub-hosted
    runners include. It reads the repository from GITHUB_REPOSITORY (set in every run) and the token
    from GH_TOKEN, which the workflow maps into this step only, on a job that may comment:

        permissions:
          contents: read
          pull-requests: write
        ...
        - run: ./scripts/post-pr-comment.ps1 -BodyPath summary.md -PullRequest $env:PR_NUMBER
          env:
            GH_TOKEN: ${{ github.token }}
            PR_NUMBER: ${{ github.event.pull_request.number }}

    Every comment ends with a footer that labels it as AI-generated and carries a marker. When the
    token's account (github-actions[bot] for the run's own token) already left a comment with the same
    marker on the pull request, the script edits that comment instead of adding one on every push.
    Comments by anyone else, even ones that quote the marker, are left alone.

    Use -WhatIf to see what would be posted without calling GitHub.

.EXAMPLE
    ./scripts/post-pr-comment.ps1 -BodyPath pr-summary.md -PullRequest 12 -Marker ai-pr-summary

.EXAMPLE
    ./scripts/post-pr-comment.ps1 -BodyPath sample.md -PullRequest 1 -WhatIf
#>
[CmdletBinding(SupportsShouldProcess)]
param(
    [Parameter(Mandatory)]
    [string] $BodyPath,

    [Parameter(Mandatory)]
    [ValidateRange(1, [int]::MaxValue)]
    [int] $PullRequest,

    # Identifies this kind of comment so later runs update it instead of adding another.
    [ValidatePattern('^[a-z0-9-]+$')]
    [string] $Marker = 'ai-comment',

    # Whose earlier comment may be updated. The run's own token comments as github-actions[bot].
    [string] $Author = 'github-actions[bot]',

    [string] $Repository = $env:GITHUB_REPOSITORY,

    # GitHub rejects comments over 65,536 characters; a longer agent answer is cut, not lost silently.
    [ValidateRange(1000, 65000)]
    [int] $MaxLength = 60000
)

$ErrorActionPreference = 'Stop'

$body = if (Test-Path -LiteralPath $BodyPath) { Get-Content -LiteralPath $BodyPath -Raw } else { $null }
if ([string]::IsNullOrWhiteSpace($body)) {
    Write-Output "::warning::$BodyPath is missing or empty; nothing to post."
    exit 0
}

$run = if ($env:GITHUB_RUN_ID) { "workflow run $env:GITHUB_RUN_ID" } else { 'a local run' }
$tag = "[$Marker]"
$footer = "`n`n---`n_AI-generated by $run and not verified by a person. ${tag}_"
$body = $body.TrimEnd()
$room = $MaxLength - $footer.Length
if ($body.Length -gt $room) {
    $note = "`n`n[Cut to $MaxLength characters.]"
    $body = $body.Substring(0, $room - $note.Length) + $note
}
$content = $body + $footer
$repo = if ($Repository) { $Repository } else { '<owner>/<repo>' }

if ($WhatIfPreference) {
    Write-Host "gh pr comment $PullRequest --repo $repo --body-file <temp file>"
    Write-Host "  (or edit the earlier comment by $Author tagged $tag)"
    Write-Host ('----- comment body: {0} characters -----' -f $content.Length)
    Write-Host $content
    Write-Host '-----'
}

if (-not $PSCmdlet.ShouldProcess("pull request #$PullRequest in $repo", "post or update the $Marker comment")) {
    exit 0
}

if (-not (Get-Command gh -ErrorAction SilentlyContinue)) {
    throw 'The GitHub CLI (gh) is not on PATH. GitHub-hosted runners include it; on your machine, install it from https://cli.github.com.'
}
if ([string]::IsNullOrWhiteSpace($env:GH_TOKEN)) {
    throw 'No token in GH_TOKEN. Map it into this step with env: GH_TOKEN: ${{ github.token }}, and give the job permissions: pull-requests: write.'
}
if ([string]::IsNullOrWhiteSpace($Repository)) {
    throw 'No repository. GITHUB_REPOSITORY is set in every GitHub Actions run; on your machine, pass -Repository <owner>/<repo>.'
}

$file = New-TemporaryFile
try {
    Set-Content -LiteralPath $file -Value $content -Encoding utf8NoBOM

    # Pull request comments are issue comments in the REST API. Find this account's earlier one.
    $filter = ".[] | select(.user.login == `"$Author`" and (.body | contains(`"$tag`"))) | .id"
    $ids = @(gh api "repos/$Repository/issues/$PullRequest/comments" --paginate --jq $filter)
    if ($LASTEXITCODE -ne 0) {
        throw "Couldn't read the comments on pull request #$PullRequest (gh exited with $LASTEXITCODE). Does the job have pull-requests: write?"
    }

    if ($ids.Count -gt 0) {
        $id = $ids[0]
        gh api --method PATCH "repos/$Repository/issues/comments/$id" -F "body=@$file" --silent
        if ($LASTEXITCODE -ne 0) { throw "Couldn't update comment $id (gh exited with $LASTEXITCODE)." }
        Write-Output "Updated comment $id on pull request #$PullRequest."
    }
    else {
        gh pr comment $PullRequest --repo $Repository --body-file $file
        if ($LASTEXITCODE -ne 0) { throw "Couldn't comment on pull request #$PullRequest (gh exited with $LASTEXITCODE)." }
    }
}
finally {
    Remove-Item -LiteralPath $file -ErrorAction SilentlyContinue
}
